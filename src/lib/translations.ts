export function translate(
  value: string,
  lang: Language,
  parameters: string[] = [],
) {
  const text = lang === "en" ? (en[value] ?? value) : value;
  return text.replace(/\{(\d+)\}/g, (token, index) =>
    parameters[Number(index)] === undefined ? token : parameters[Number(index)],
  );
}
